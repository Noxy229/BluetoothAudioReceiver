    private Dictionary<string, string>? GetTranslation(string languageCode)
    {
        lock (_lock)
        {
            if (_loadedTranslations.TryGetValue(languageCode, out var dict))
            {
                return dict;
            }

            dict = LoadTranslation(languageCode);
            if (dict != null)
            {
                _loadedTranslations[languageCode] = dict;
            }
            return dict;
        }
    }

